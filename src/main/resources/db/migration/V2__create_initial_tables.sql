
CREATE TABLE UNIDADE_OPERACIONAL (
                                     ID_UNIDADE            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                     NOME                  VARCHAR2(100) NOT NULL,
                                     CIDADE                VARCHAR2(60)  NOT NULL,
                                     UF                    CHAR(2)       NOT NULL,
                                     SETOR                 VARCHAR2(50)  NOT NULL,
                                     LIMITE_CO2_MENSAL     NUMBER(12,3)  NOT NULL,
                                     EMISSAO_ACUMULADA_MES NUMBER(12,3)  DEFAULT 0 NOT NULL,
                                     MES_REFERENCIA        CHAR(7),
                                     CONSTRAINT PK_UNIDADE PRIMARY KEY (ID_UNIDADE),
                                     CONSTRAINT CK_UNIDADE_LIMITE CHECK (LIMITE_CO2_MENSAL > 0),
                                     CONSTRAINT CK_UNIDADE_ACUM   CHECK (EMISSAO_ACUMULADA_MES >= 0)
);

CREATE TABLE LICENCA_AMBIENTAL (
                                   ID_LICENCA     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                   ID_UNIDADE     NUMBER        NOT NULL,
                                   NUMERO         VARCHAR2(30)  NOT NULL,
                                   TIPO           CHAR(2)       NOT NULL,
                                   ORGAO_EMISSOR  VARCHAR2(60)  NOT NULL,
                                   DATA_EMISSAO   DATE          NOT NULL,
                                   DATA_VALIDADE  DATE          NOT NULL,
                                   STATUS         VARCHAR2(12),
                                   CONSTRAINT PK_LICENCA PRIMARY KEY (ID_LICENCA),
                                   CONSTRAINT FK_LICENCA_UNIDADE FOREIGN KEY (ID_UNIDADE)
                                       REFERENCES UNIDADE_OPERACIONAL (ID_UNIDADE),
                                   CONSTRAINT UQ_LICENCA_NUMERO UNIQUE (NUMERO),
                                   CONSTRAINT CK_LICENCA_TIPO   CHECK (TIPO IN ('LP','LI','LO')),
                                   CONSTRAINT CK_LICENCA_STATUS CHECK (STATUS IN ('VIGENTE','A_RENOVAR','VENCIDA','SUSPENSA')),
                                   CONSTRAINT CK_LICENCA_DATAS  CHECK (DATA_VALIDADE > DATA_EMISSAO)
);

CREATE TABLE EMISSAO_CARBONO (
                                 ID_EMISSAO     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                 ID_UNIDADE     NUMBER        NOT NULL,
                                 DATA_REGISTRO  DATE          DEFAULT SYSDATE NOT NULL,
                                 FONTE          VARCHAR2(20)  NOT NULL,
                                 ESCOPO         NUMBER(1)     NOT NULL,
                                 QTD_TCO2E      NUMBER(12,3)  NOT NULL,
                                 CONSTRAINT PK_EMISSAO PRIMARY KEY (ID_EMISSAO),
                                 CONSTRAINT FK_EMISSAO_UNIDADE FOREIGN KEY (ID_UNIDADE)
                                     REFERENCES UNIDADE_OPERACIONAL (ID_UNIDADE),
                                 CONSTRAINT CK_EMISSAO_FONTE  CHECK (FONTE IN ('DIESEL','GASOLINA','GAS_NATURAL',
                                                                               'ENERGIA_ELETRICA','GLP','PROCESSO')),
                                 CONSTRAINT CK_EMISSAO_ESCOPO CHECK (ESCOPO IN (1,2,3)),
                                 CONSTRAINT CK_EMISSAO_QTD    CHECK (QTD_TCO2E > 0)
);

CREATE TABLE COMPENSACAO_CARBONO (
                                     ID_COMPENSACAO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                     ID_UNIDADE     NUMBER        NOT NULL,
                                     PROJETO        VARCHAR2(30)  NOT NULL,
                                     QTD_TCO2E      NUMBER(12,3)  NOT NULL,
                                     DATA_REGISTRO  DATE          DEFAULT SYSDATE NOT NULL,
                                     STATUS         VARCHAR2(12)  DEFAULT 'PENDENTE' NOT NULL,
                                     ORIGEM         VARCHAR2(10)  DEFAULT 'MANUAL' NOT NULL,  -- MANUAL / AUTOMATICA
                                     CONSTRAINT PK_COMPENSACAO PRIMARY KEY (ID_COMPENSACAO),
                                     CONSTRAINT FK_COMPENSACAO_UNIDADE FOREIGN KEY (ID_UNIDADE)
                                         REFERENCES UNIDADE_OPERACIONAL (ID_UNIDADE),
                                     CONSTRAINT CK_COMP_PROJETO CHECK (PROJETO IN ('REFLORESTAMENTO','CREDITO_CARBONO',
                                                                                   'ENERGIA_RENOVAVEL','A_DEFINIR')),
                                     CONSTRAINT CK_COMP_STATUS  CHECK (STATUS IN ('PENDENTE','EM_ANDAMENTO','CONCLUIDA')),
                                     CONSTRAINT CK_COMP_ORIGEM  CHECK (ORIGEM IN ('MANUAL','AUTOMATICA')),
                                     CONSTRAINT CK_COMP_QTD     CHECK (QTD_TCO2E > 0)
);

CREATE TABLE ALERTA_COMPLIANCE (
                                   ID_ALERTA      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                                   ID_UNIDADE     NUMBER         NOT NULL,
                                   TIPO_ALERTA    VARCHAR2(30)   NOT NULL,
                                   DESCRICAO      VARCHAR2(400)  NOT NULL,
                                   DATA_ALERTA    DATE           DEFAULT SYSDATE NOT NULL,
                                   STATUS         VARCHAR2(10)   DEFAULT 'ABERTO' NOT NULL,
                                   CONSTRAINT PK_ALERTA PRIMARY KEY (ID_ALERTA),
                                   CONSTRAINT FK_ALERTA_UNIDADE FOREIGN KEY (ID_UNIDADE)
                                       REFERENCES UNIDADE_OPERACIONAL (ID_UNIDADE),
                                   CONSTRAINT CK_ALERTA_TIPO   CHECK (TIPO_ALERTA IN ('RENOVACAO_LICENCA','LICENCA_VENCIDA',
                                                                                      'LIMITE_EMISSAO','OPERACAO_SEM_LICENCA',
                                                                                      'AUDITORIA_INTERNA')),
                                   CONSTRAINT CK_ALERTA_STATUS CHECK (STATUS IN ('ABERTO','EM_ANALISE','RESOLVIDO'))
);

CREATE OR REPLACE PROCEDURE PRC_REGISTRA_ALERTA (
  P_ID_UNIDADE  IN NUMBER,
  P_TIPO        IN VARCHAR2,
  P_DESCRICAO   IN VARCHAR2
) IS
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
INSERT INTO ALERTA_COMPLIANCE (ID_UNIDADE, TIPO_ALERTA, DESCRICAO, DATA_ALERTA, STATUS)
VALUES (P_ID_UNIDADE, P_TIPO, P_DESCRICAO, SYSDATE, 'ABERTO');
COMMIT;
END;
/

CREATE OR REPLACE TRIGGER TRG_STATUS_LICENCA
BEFORE INSERT OR UPDATE ON LICENCA_AMBIENTAL
                            REFERENCING NEW AS NEW OLD AS OLD
                            FOR EACH ROW
BEGIN
  IF :NEW.STATUS = 'SUSPENSA' THEN
    RETURN;
END IF;

  IF TRUNC(:NEW.DATA_VALIDADE) < TRUNC(SYSDATE) THEN
    :NEW.STATUS := 'VENCIDA';
  ELSIF TRUNC(:NEW.DATA_VALIDADE) <= TRUNC(SYSDATE) + 120 THEN
    :NEW.STATUS := 'A_RENOVAR';
ELSE
    :NEW.STATUS := 'VIGENTE';
END IF;

  IF :NEW.STATUS = 'A_RENOVAR' AND NVL(:OLD.STATUS, 'X') <> 'A_RENOVAR' THEN
    INSERT INTO ALERTA_COMPLIANCE (ID_UNIDADE, TIPO_ALERTA, DESCRICAO, DATA_ALERTA, STATUS)
    VALUES (:NEW.ID_UNIDADE, 'RENOVACAO_LICENCA',
            'Licença ' || :NEW.TIPO || ' nº ' || :NEW.NUMERO || ' vence em ' ||
            TO_CHAR(:NEW.DATA_VALIDADE, 'DD/MM/YYYY') || ' (' ||
            TO_CHAR(TRUNC(:NEW.DATA_VALIDADE) - TRUNC(SYSDATE)) ||
            ' dias). Protocolar pedido de renovação (CONAMA 237/97).',
            SYSDATE, 'ABERTO');
  ELSIF :NEW.STATUS = 'VENCIDA' AND NVL(:OLD.STATUS, 'X') <> 'VENCIDA' THEN
    INSERT INTO ALERTA_COMPLIANCE (ID_UNIDADE, TIPO_ALERTA, DESCRICAO, DATA_ALERTA, STATUS)
    VALUES (:NEW.ID_UNIDADE, 'LICENCA_VENCIDA',
            'Licença ' || :NEW.TIPO || ' nº ' || :NEW.NUMERO || ' vencida desde ' ||
            TO_CHAR(:NEW.DATA_VALIDADE, 'DD/MM/YYYY') || '.',
            SYSDATE, 'ABERTO');
END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_BLOQUEIO_SEM_LICENCA
BEFORE INSERT ON EMISSAO_CARBONO
REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
DECLARE
V_QTD_LO   NUMBER;
  V_NOME     UNIDADE_OPERACIONAL.NOME%TYPE;
BEGIN
SELECT COUNT(*)
INTO V_QTD_LO
FROM LICENCA_AMBIENTAL
WHERE ID_UNIDADE = :NEW.ID_UNIDADE
  AND TIPO       = 'LO'
  AND STATUS    <> 'SUSPENSA'
  AND TRUNC(:NEW.DATA_REGISTRO) BETWEEN TRUNC(DATA_EMISSAO) AND TRUNC(DATA_VALIDADE);

IF V_QTD_LO = 0 THEN
SELECT NOME INTO V_NOME
FROM UNIDADE_OPERACIONAL
WHERE ID_UNIDADE = :NEW.ID_UNIDADE;

PRC_REGISTRA_ALERTA(:NEW.ID_UNIDADE, 'OPERACAO_SEM_LICENCA',
      'Tentativa de registrar ' || TO_CHAR(:NEW.QTD_TCO2E) || ' tCO2e (' || :NEW.FONTE ||
      ') na unidade "' || V_NOME || '" sem Licença de Operação válida. Registro bloqueado.');

    RAISE_APPLICATION_ERROR(-20001,
      'Unidade ' || :NEW.ID_UNIDADE || ' (' || V_NOME ||
      ') sem Licença de Operação válida. Operação bloqueada.');
END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_ALERTA_LIMITE_EMISSAO
BEFORE INSERT ON EMISSAO_CARBONO
REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
FOLLOWS TRG_BLOQUEIO_SEM_LICENCA
DECLARE
V_LIMITE     UNIDADE_OPERACIONAL.LIMITE_CO2_MENSAL%TYPE;
  V_ACUMULADO  UNIDADE_OPERACIONAL.EMISSAO_ACUMULADA_MES%TYPE;
  V_MES_REF    UNIDADE_OPERACIONAL.MES_REFERENCIA%TYPE;
  V_MES_NOVO   CHAR(7) := TO_CHAR(:NEW.DATA_REGISTRO, 'YYYY-MM');
BEGIN
SELECT LIMITE_CO2_MENSAL, EMISSAO_ACUMULADA_MES, MES_REFERENCIA
INTO V_LIMITE, V_ACUMULADO, V_MES_REF
FROM UNIDADE_OPERACIONAL
WHERE ID_UNIDADE = :NEW.ID_UNIDADE
    FOR UPDATE;

IF V_MES_REF IS NULL OR V_MES_REF <> V_MES_NOVO THEN
    V_ACUMULADO := 0;
END IF;

  V_ACUMULADO := V_ACUMULADO + :NEW.QTD_TCO2E;

UPDATE UNIDADE_OPERACIONAL
SET EMISSAO_ACUMULADA_MES = V_ACUMULADO,
    MES_REFERENCIA        = V_MES_NOVO
WHERE ID_UNIDADE = :NEW.ID_UNIDADE;

IF V_ACUMULADO > V_LIMITE THEN
    INSERT INTO ALERTA_COMPLIANCE (ID_UNIDADE, TIPO_ALERTA, DESCRICAO, DATA_ALERTA, STATUS)
    VALUES (:NEW.ID_UNIDADE, 'LIMITE_EMISSAO',
            'Emissão acumulada de ' || V_MES_NOVO || ' = ' || TO_CHAR(V_ACUMULADO) ||
            ' tCO2e, acima do limite de ' || TO_CHAR(V_LIMITE) ||
            ' tCO2e (excedente: ' || TO_CHAR(V_ACUMULADO - V_LIMITE) || ' tCO2e).',
            SYSDATE, 'ABERTO');
END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_COMPENSACAO_AUTOMATICA
AFTER UPDATE OF EMISSAO_ACUMULADA_MES ON UNIDADE_OPERACIONAL
    REFERENCING NEW AS NEW OLD AS OLD
    FOR EACH ROW
DECLARE
V_EXCEDENTE_ANT  NUMBER := 0;
  V_EXCEDENTE_NOVO NUMBER;
BEGIN

  IF :OLD.MES_REFERENCIA = :NEW.MES_REFERENCIA THEN
    V_EXCEDENTE_ANT := GREATEST(:OLD.EMISSAO_ACUMULADA_MES - :OLD.LIMITE_CO2_MENSAL, 0);
END IF;

  V_EXCEDENTE_NOVO := GREATEST(:NEW.EMISSAO_ACUMULADA_MES - :NEW.LIMITE_CO2_MENSAL, 0);

  IF V_EXCEDENTE_NOVO > V_EXCEDENTE_ANT THEN
    INSERT INTO COMPENSACAO_CARBONO
           (ID_UNIDADE, PROJETO, QTD_TCO2E, DATA_REGISTRO, STATUS, ORIGEM)
    VALUES (:NEW.ID_UNIDADE, 'A_DEFINIR', V_EXCEDENTE_NOVO - V_EXCEDENTE_ANT,
            SYSDATE, 'PENDENTE', 'AUTOMATICA');
END IF;
END;
/

